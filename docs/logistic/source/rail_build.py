def track(x, width_px, label, country):
    """Поперечник пути: шпала, две рельсы, размерная линия между внутренними гранями."""
    half = width_px / 2
    cx = x + 130
    rail_w = 9
    left = cx - half
    right = cx + half
    svg = f'''
      <rect class="sleeper" x="{cx - half - 26:.0f}" y="74" width="{width_px + 52:.0f}" height="13" rx="1"/>
      <rect class="rail" x="{left - rail_w:.0f}" y="56" width="{rail_w}" height="20" rx="1.5"/>
      <rect class="rail" x="{right:.0f}" y="56" width="{rail_w}" height="20" rx="1.5"/>
      <line class="dim" x1="{left:.0f}" y1="42" x2="{right:.0f}" y2="42"/>
      <line class="dim" x1="{left:.0f}" y1="36" x2="{left:.0f}" y2="56"/>
      <line class="dim" x1="{right:.0f}" y1="36" x2="{right:.0f}" y2="56"/>
      <text class="dimtext" x="{cx:.0f}" y="30" text-anchor="middle">{label}</text>
      <text class="country" x="{cx:.0f}" y="106" text-anchor="middle">{country}</text>'''
    # Без обрезки в HTML остаются висячие пробелы, и `git diff --check` на них ругается.
    return "\n".join(line.rstrip() for line in svg.splitlines())


