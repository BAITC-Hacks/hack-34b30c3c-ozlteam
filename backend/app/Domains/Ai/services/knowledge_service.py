def list_articles() -> list[dict[str, str]]:
    """Return independent public copies of the curated, non-sensitive corpus."""
    return [article.public() for article in _ARTICLES]


def get_article(article_id: str) -> dict[str, str] | None:
    """Resolve a fixed article ID; never open a user-provided filesystem path."""
    return next((article.public() for article in _ARTICLES if article.id == article_id), None)


def search_help(query: str) -> list[dict[str, str]]:
    """Retrieve up to three articles by explicit Russian/English keyword prefixes.

    Only curated topic keywords score, not generic words in article prose. Unknown
    topics return no evidence rather than a fabricated best match. Stable corpus
    order breaks ties and result snippets retain their title and product route.
    """
    tokens = set(
        re.findall(r"[а-яa-z0-9_]+", query[:MAX_QUERY_LENGTH].casefold().replace("ё", "е"))
    )
    scored = []
    for index, article in enumerate(_ARTICLES):
        score = sum(
            any(token.startswith(keyword) for token in tokens) for keyword in article.keywords
        )
        if score:
            scored.append((score, index, article))
    scored.sort(key=lambda item: (-item[0], item[1]))
    return [article.public() for _, _, article in scored[:MAX_RESULTS]]
