/**
 * География карты рейсов: контуры стран, водоёмы и дорожные коридоры.
 *
 * Карта рисуется своим SVG-рендерером, без тайлов и сетевых слоёв, поэтому вся
 * геометрия лежит здесь, в градусах WGS 84. Контуры сильно упрощены: на масштабе
 * всего региона (79° по долготе в кадр шириной около тысячи пикселей) один градус
 * это единицы пикселей, и лишние вершины дают только вес файла. Задача силуэта —
 * чтобы страна узнавалась и город стоял на своей территории, а не чтобы по нему
 * можно было провести границу.
 *
 * Главное правило файла: общие участки границы соседи берут из одного и того же
 * массива, а тройные стыки — из одной и той же константы. Если у двух заливок
 * хоть на сотую градуса разойдутся вершины, между странами появится белый волос,
 * который на карте заметнее любой неточности силуэта.
 *
 * Расстояния в коридорах — по дороге, а не по прямой: план рейса считается по ним,
 * и хорда занизила бы километраж на 15–25% везде, где трасса обходит горы или озеро.
 */

import type { Corridor, CountryCode, GeoPoint } from "../types";

